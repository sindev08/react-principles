/**
 * sync-registry.mjs
 *
 * Single source of truth → generated consumers.
 *  - Component source lives in src/ui/*.tsx (+ cn util, animated-mount hook).
 *  - Component metadata lives in src/lib/ui-registry.json.
 *
 * This script transforms the source (@/ imports → CLI aliases) and writes:
 *  - packages/cli/src/registry/templates.ts       (CLI: component source)
 *  - packages/cli/src/registry/registry-data.json (CLI: metadata copy)
 *  - src/lib/ui-templates.generated.ts            (site: component source for MCP)
 *
 * The site imports src/lib/ui-registry.json directly. Run before building
 * the CLI (wired as its prebuild):
 *   node scripts/sync-registry.mjs
 */

import { readFileSync, writeFileSync, readdirSync } from "fs";
import { join, basename } from "path";
import { fileURLToPath } from "url";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const ROOT = join(__dirname, "..");

const UI_DIR = join(ROOT, "src/ui");
const CN_SRC = join(ROOT, "src/shared/utils/cn.ts");
const HOOK_SRC = join(ROOT, "src/shared/hooks/useAnimatedMount.ts");
const REGISTRY_SRC = join(ROOT, "src/lib/ui-registry.json");

const CLI_TEMPLATES_OUT = join(ROOT, "packages/cli/src/registry/templates.ts");
const CLI_REGISTRY_OUT = join(ROOT, "packages/cli/src/registry/registry-data.json");
const SITE_TEMPLATES_OUT = join(ROOT, "src/lib/ui-templates.generated.ts");

function transform(src) {
  return src
    .replace(/from "@\/shared\/utils\/cn"/g, 'from "@/lib/utils"')
    .replace(/from "@\/shared\/hooks\/useAnimatedMount"/g, 'from "@/hooks/use-animated-mount"');
}

function escape(str) {
  return str.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

const templates = {};

// utils + shared hook
templates["utils"] = escape(readFileSync(CN_SRC, "utf8").trim());
templates["use-animated-mount"] = escape(readFileSync(HOOK_SRC, "utf8").trim());

// ui components
const files = readdirSync(UI_DIR).filter(
  (f) => f.endsWith(".tsx") && !f.includes(".stories.") && !f.includes(".test.")
);
for (const file of files) {
  const name = basename(file, ".tsx");
  const raw = readFileSync(join(UI_DIR, file), "utf8").trim();
  templates[name] = escape(transform(raw));
}

function templatesModule(exportName) {
  return [
    "// AUTO-GENERATED by scripts/sync-registry.mjs — do not edit manually",
    "",
    `export const ${exportName}: Record<string, string> = {`,
    ...Object.entries(templates).map(([k, v]) => `  "${k}": \`${v}\`,`),
    "};",
    "",
  ].join("\n");
}

// CLI: component source
writeFileSync(CLI_TEMPLATES_OUT, templatesModule("TEMPLATES"), "utf8");
// Site: component source for the MCP server
writeFileSync(SITE_TEMPLATES_OUT, templatesModule("UI_TEMPLATES"), "utf8");

// CLI: self-contained metadata copy (site owns the source of truth)
const registryJson = readFileSync(REGISTRY_SRC, "utf8");
writeFileSync(CLI_REGISTRY_OUT, registryJson, "utf8");

const count = Object.keys(templates).length;
console.log(
  `✓ Synced ${count} templates → CLI + site, and mirrored ui-registry.json → CLI`,
);
